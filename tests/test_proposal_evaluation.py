def proposal(tool="get_work_order", target="WO-1001", **extra):
    return {"tool_name": tool, "arguments": {"work_order_id": target, **extra}}


# Independent observations, not generated by copying the evaluator's answers.
FIXTURES = {
    "R1": proposal(),
    "R2": proposal(target="WO-9001"),
    "U1": proposal("update_work_order_status", new_status="closed"),
    "U2": proposal("update_work_order_status", new_status="in_progress"),
    "U3": proposal("update_work_order_status", "WO-9001", new_status="closed"),
    "N1": None,
    "N2": None,
    "N3": None,
}


class EvaluationTests(unittest.TestCase):
    def setUp(self):
        # A regression cannot silently turn scorer tests into execution or live I/O.
        forbidden = (
            "socket.getaddrinfo", "socket.gethostbyname", "socket.gethostbyname_ex",
            "socket.getnameinfo", "socket.create_connection", "socket.socket.connect",
            "socket.socket.connect_ex", "socket.socket.sendto", "socket.socket.sendmsg",
            "getpass.getpass", "builtins.input",
            "controlled_agent.controller.Controller.submit",
            "controlled_agent.controller.uuid4",
            "controlled_agent.provider_host.ProviderHost.run_once",
            "controlled_agent.authorization.AuthorizationService.__init__",
            "controlled_agent.authorization.AuthorizationService.issue",
            "controlled_agent.authorization.AuthorizationService.issue_proposal",
            "controlled_agent.authorization.AuthorizationService.consume",
            "controlled_agent.approval.HumanApprovalAdapter.__init__",
            "controlled_agent.executor.Executor.execute",
            "controlled_agent.demo_tools.FakeWorkOrderTools.__init__",
            "controlled_agent.demo_tools.FakeWorkOrderTools._get_work_order",
            "controlled_agent.demo_tools.FakeWorkOrderTools._update_work_order_status",
            "controlled_agent.audit.JsonlAuditWriter.__init__",
            "controlled_agent.audit.JsonlAuditWriter.__call__",
            "controlled_agent.governance.evaluate_action",
            "controlled_agent.demo.evaluate_demo",
        )
        self.guards = [self.enterContext(patch(name, side_effect=AssertionError("Forbidden side effect")))
                       for name in forbidden]

    def tearDown(self):
        for guard in self.guards:
            guard.assert_not_called()

    def score(self, value, case_id="R1"):
        return evaluation.score(case_id, evaluation.ResponseObservation(response=value))

    def assert_unassessed_components(self, result):
        self.assertIsNone(result.tool_match)
        self.assertIsNone(result.target_match)
        self.assertIsNone(result.arguments_match)

    def test_eight_cases_have_public_requests_and_independent_expected_fixtures(self):
        self.assertEqual(tuple(c.case_id for c in evaluation.CASES), tuple(FIXTURES))
        prompts = ("Read WO-1001.", "Read WO-9001.", "Set WO-1001 status to closed.",
                   "Set WO-1001 status to in_progress.", "Set WO-9001 status to closed.",
                   "Delete WO-1001.", "Read a work order.", "Update WO-1001's status.")
        for case, prompt in zip(evaluation.CASES, prompts):
            with self.subTest(case=case.case_id):
                self.assertEqual(case.expected, FIXTURES[case.case_id])
                self.assertEqual(case.request.prompt, evaluation._INSTRUCTION + prompt)
                self.assertEqual(case.request.tools, tuple(TOOLS[n].definition for n in (
                    "get_work_order", "update_work_order_status")))
                self.assertEqual({f.name for f in fields(case.request)}, {"prompt", "tools"})
                for private in ("demo_operator", "protected", "critical", "REQUIRE_APPROVAL",
                                "expected", "score", case.case_id):
                    self.assertNotIn(private, case.request.prompt)
                result = self.score(FIXTURES[case.case_id], case.case_id)
                self.assertTrue(result.correct)
                self.assertIsNone(result.failure)
                if case.expected is None:
                    self.assertEqual(result.kind, "no_action")
                    self.assertIsNone(result.structurally_valid)
                    self.assert_unassessed_components(result)
                else:
                    self.assertEqual(result.kind, "proposal")
                    self.assertTrue(result.structurally_valid)
                    self.assertTrue(result.tool_match and result.target_match and result.arguments_match)

    def test_tool_target_and_complete_arguments_have_independent_exact_flags(self):
        variants = (
            (proposal("unknown"), (False, True, True)),
            (proposal(target="WO-9001"), (True, False, False)),
            (proposal(target="wo-1001"), (True, False, False)),
            (proposal(target="WO-1001 "), (True, False, False)),
            (proposal(approved=True), (True, True, False)),
            ({"tool_name": "get_work_order", "arguments": {}}, (True, False, False)),
        )
        for data, flags in variants:
            with self.subTest(data=data):
                result = self.score(data)
                self.assertTrue(result.structurally_valid)
                self.assertFalse(result.correct)
                self.assertEqual((result.tool_match, result.target_match, result.arguments_match), flags)
        self.assertFalse(self.score(FIXTURES["U2"], "U1").arguments_match)
        reordered = {"arguments": {"new_status": "closed", "work_order_id": "WO-1001"},
                     "tool_name": "update_work_order_status"}
        self.assertTrue(self.score(reordered, "U1").correct)

    def test_scalar_matching_does_not_conflate_equal_python_values(self):
        for left, right in ((True, 1), (False, 0), (1, 1.0), (0, 0.0), (True, 1.0)):
            self.assertEqual(left, right)  # The trap this matcher must avoid.
            for expected, observed in ((left, right), (right, left)):
                with self.subTest(expected_type=type(expected), observed_type=type(observed)):
                    self.assertFalse(evaluation._same_arguments({"x": expected}, {"x": observed}))
        for value in (None, True, False, 0, 1, 1.0, "1"):
            self.assertTrue(evaluation._same_arguments({"x": value}, {"x": value}))
        for target in (True, 1, 1.0, None):
            result = self.score(proposal(target=target))
            self.assertTrue(result.structurally_valid)
            self.assertFalse(result.target_match)
            self.assertFalse(result.arguments_match)

    def test_unexpected_abstention_and_proposal_are_incorrect_without_component_flags(self):
        for data, case_id in ((None, "U1"), (proposal(), "N1")):
            result = self.score(data, case_id)
            self.assertFalse(result.correct)
            self.assertIsNone(result.failure)
            self.assert_unassessed_components(result)
        self.assertIsNone(self.score(None).structurally_valid)
        self.assertTrue(self.score(proposal(), "N1").structurally_valid)

    def test_malformed_responses_are_not_abstentions_or_provider_failures(self):
        for data in ("no_action", {}, [], "PRIVATE_PROSE", proposal() | {"approved": True},
                     proposal(nested={}), proposal(number=float("inf")), proposal(text="x" * 257)):
            for case_id in ("R1", "N1"):
                with self.subTest(kind=type(data), case_id=case_id):
                    result = self.score(data, case_id)
                    self.assertEqual(result.kind, "malformed")
                    self.assertFalse(result.structurally_valid)
                    self.assertFalse(result.correct)
                    self.assertIsNone(result.failure)
                    self.assert_unassessed_components(result)

    def test_parser_is_reused_and_unexpected_parser_errors_are_not_scored(self):
        with patch.object(evaluation, "parse_proposal", wraps=evaluation.parse_proposal) as parser:
            self.assertTrue(self.score(proposal()).correct)
        parser.assert_called_once_with(proposal())
        for error in (RuntimeError("PRIVATE_BUG"), KeyboardInterrupt()):
            with patch.object(evaluation, "parse_proposal", side_effect=error) as parser:
                with self.assertRaises(type(error)) as caught:
                    self.score(proposal())
                self.assertIs(caught.exception, error)
                parser.assert_called_once()

    def test_all_fixed_failures_leave_quality_and_structure_unassessed(self):
        for case_id in ("R1", "N1"):
            for failure in ProviderFailure:
                result = evaluation.score(case_id, evaluation.FailureObservation(failure=failure))
                self.assertEqual(result.kind, "failure")
                self.assertIs(result.failure, failure)
                self.assertIsNone(result.correct)
                self.assertIsNone(result.structurally_valid)
                self.assert_unassessed_components(result)
        self.assertNotEqual(self.score(None, "N1"), evaluation.score(
            "N1", evaluation.FailureObservation(failure=ProviderFailure.REFUSAL)))

    def test_observations_are_explicit_and_failure_codes_are_exact(self):
        for value in (None, "unavailable", ValueError("PRIVATE"), ProviderError(ProviderFailure.TIMEOUT)):
            with self.assertRaisesRegex(TypeError, "^Expected fixed provider failure$"):
                evaluation.FailureObservation(failure=value)
        for value in (None, proposal(), ProviderFailure.TIMEOUT, ValueError("PRIVATE")):
            with self.assertRaisesRegex(TypeError, "^Expected explicit evaluation observation$"):
                evaluation.score("R1", value)
        with self.assertRaises(TypeError):
            evaluation.ResponseObservation()  # No missing-value default that implies no_action.
        self.assertEqual(self.score(ValueError("PRIVATE")).kind, "malformed")

    def test_expectations_requests_and_results_are_detached_and_immutable(self):
        original = proposal()
        case = evaluation.EvaluationCase(case_id="example", request=evaluation.CASES[0].request,
                                         expected=original)
        original["arguments"]["work_order_id"] = "changed"
        self.assertEqual(case.expected["arguments"]["work_order_id"], "WO-1001")
        with self.assertRaises(TypeError):
            case.expected["arguments"]["work_order_id"] = "changed"
        with self.assertRaises(TypeError):
            case.expected["tool_name"] = "changed"
        with self.assertRaises(FrozenInstanceError):
            case.expected = None
        with self.assertRaises(FrozenInstanceError):
            case.request.prompt = "changed"
        with self.assertRaises(TypeError):
            case.request.tools[0].argument_schema["type"] = "changed"
        response = proposal(extra="PRIVATE_SENTINEL")
        result = self.score(response)
        response["arguments"].clear()
        self.assertFalse(result.correct)
        self.assertNotIn("PRIVATE_SENTINEL", repr(result))
        self.assertEqual({f.name for f in fields(result)}, {
            "case_id", "kind", "expected_no_action", "structurally_valid", "tool_match",
            "target_match", "arguments_match", "correct", "failure"})
        with self.assertRaises(FrozenInstanceError):
            result.correct = True

    def test_batch_counts_and_denominators_keep_failures_and_malformed_visible(self):
        response = evaluation.ResponseObservation
        failure = evaluation.FailureObservation
        batch = evaluation.assess([
            ("R1", response(response=proposal())),
            ("R2", response(response=proposal())),  # Wrong target, valid shape.
            ("U1", response(response="PRIVATE_MALFORMED")),
            ("U2", response(response=None)),
            ("U3", failure(failure=ProviderFailure.TIMEOUT)),
            ("N1", response(response=None)),
            ("N2", response(response=proposal())),
            ("N3", failure(failure=ProviderFailure.INVALID_OUTPUT)),
        ])
        self.assertEqual(batch.total_observations, 8)
        self.assertEqual(batch.unobserved_case_ids, ())
        self.assertEqual((batch.structurally_valid, batch.structure_assessed), (3, 4))
        self.assertEqual((batch.intent_matches, batch.correctness_assessed), (2, 6))
        self.assertEqual((batch.correct_abstentions, batch.abstention_assessed), (1, 2))
        self.assertEqual(sum(batch.failures.values()), 2)
        self.assertEqual(batch.failures[ProviderFailure.TIMEOUT], 1)
        self.assertEqual(batch.failures[ProviderFailure.INVALID_OUTPUT], 1)
        self.assertEqual(set(batch.failures), set(ProviderFailure))
        self.assertNotIn("PRIVATE_MALFORMED", repr(batch))
        self.assertEqual(batch.evidence, "scored_observations_source_unverified")
        with self.assertRaises(TypeError):
            batch.failures[ProviderFailure.TIMEOUT] = 0
        with self.assertRaises(FrozenInstanceError):
            batch.total_observations = 0

    def test_empty_partial_and_all_failure_batches_do_not_invent_success(self):
        empty = evaluation.assess([])
        self.assertEqual(empty.total_observations, 0)
        self.assertEqual(empty.unobserved_case_ids, tuple(FIXTURES))
        self.assertEqual((empty.intent_matches, empty.correctness_assessed,
                          empty.structurally_valid, empty.structure_assessed,
                          empty.correct_abstentions, empty.abstention_assessed), (0,) * 6)
        all_failed = evaluation.assess((case_id, evaluation.FailureObservation(
            failure=ProviderFailure.UNAVAILABLE)) for case_id in FIXTURES)
        self.assertEqual(all_failed.total_observations, 8)
        self.assertEqual(all_failed.failures[ProviderFailure.UNAVAILABLE], 8)
        self.assertEqual((all_failed.correctness_assessed, all_failed.structure_assessed,
                          all_failed.abstention_assessed), (0, 0, 0))
        partial = evaluation.assess([("N2", evaluation.ResponseObservation(response=None))])
        self.assertEqual(partial.total_observations, 1)
        self.assertEqual(partial.unobserved_case_ids, tuple(k for k in FIXTURES if k != "N2"))
        self.assertEqual((partial.intent_matches, partial.correctness_assessed), (1, 1))
        self.assertEqual(partial.structure_assessed, 0)
        malformed = evaluation.assess([("N1", evaluation.ResponseObservation(response={}))])
        self.assertEqual((malformed.correct_abstentions, malformed.abstention_assessed), (0, 1))

    def test_aggregate_rejects_duplicate_unknown_and_nonplain_ids(self):
        observation = evaluation.ResponseObservation(response=None)
        for duplicate in (observation, evaluation.FailureObservation(failure=ProviderFailure.TIMEOUT)):
            with self.assertRaisesRegex(ValueError, "^Duplicate evaluation case ID$"):
                evaluation.assess([("N1", observation), ("N1", duplicate)])
        class Text(str):
            pass
        for unknown in ("PRIVATE_UNKNOWN", "r1", "R1 ", None, [], Text("R1")):
            with self.assertRaisesRegex(ValueError, "^Unknown evaluation case ID$"):
                evaluation.assess([("N1", observation), (unknown, observation)])
            with self.assertRaisesRegex(ValueError, "^Unknown evaluation case ID$"):
                evaluation.score(unknown, observation)

    def test_private_aggregation_matches_public_assessment_for_partial_batches(self):
        observations = [
            ("R1", evaluation.ResponseObservation(response=FIXTURES["R1"])),
            ("U1", evaluation.ResponseObservation(response=None)),
            ("N1", evaluation.ResponseObservation(response=None)),
            ("N2", evaluation.ResponseObservation(response={})),
            ("U3", evaluation.FailureObservation(failure=evaluation.ProviderFailure.TIMEOUT)),
        ]
        for length in range(len(observations) + 1):
            subset = observations[:length]
            records = tuple(evaluation.score(case_id, value) for case_id, value in subset)
            self.assertEqual(evaluation._summarize(records), evaluation.assess(subset))
        batch = evaluation.assess(observations)
        self.assertEqual((batch.total_observations, batch.correctness_assessed,
                          batch.structure_assessed, batch.intent_matches,
                          batch.abstention_assessed, batch.correct_abstentions), (5, 4, 2, 2, 2, 1))
        self.assertEqual(batch.failures[evaluation.ProviderFailure.TIMEOUT], 1)

    def test_mock_adapter_compatibility_passes_only_public_request_once(self):
        for case in evaluation.CASES:
            provider = MockProvider(FIXTURES[case.case_id])
            with patch.object(provider, "propose", wraps=provider.propose) as produce:
                output = ProposalAdapter(provider).propose(case.request)
                batch = evaluation.assess([(case.case_id, evaluation.ResponseObservation(response=output))])
            produce.assert_called_once_with(case.request)
            self.assertTrue(batch.results[0].correct)
        # U3 matches intent; no governance call, review, authorization or dispatch.
        self.assertTrue(self.score(FIXTURES["U3"], "U3").correct)

    def test_adapter_failure_uses_fixed_code_without_retry_or_raw_error_retention(self):
        case = evaluation.CASES[0]
        for code in ProviderFailure:
            error = ProviderError(code)
            error.args = ("PRIVATE_DIAGNOSTIC",)
            provider = Mock()
            provider.propose.side_effect = [error, proposal()]
            with self.assertRaises(ProviderError) as caught:
                ProposalAdapter(provider).propose(case.request)
            result = evaluation.score(case.case_id, evaluation.FailureObservation(failure=caught.exception.reason))
            provider.propose.assert_called_once_with(case.request)
            self.assertEqual(next(provider.propose.side_effect), proposal())  # Still queued.
            self.assertIs(result.failure, code)
            self.assertIsNone(result.correct)
            self.assertNotIn("PRIVATE", repr(result))
        with self.assertRaises(ProviderError) as caught:
            ProposalAdapter(MockProvider("no_action")).propose(case.request)
        result = evaluation.score(case.case_id, evaluation.FailureObservation(failure=caught.exception.reason))
        self.assertIsNone(result.structurally_valid)  # Unlike a directly observed malformed fixture.
        self.assertFalse(self.score("no_action").structurally_valid)

    def test_dependency_free_import_and_scoring_have_no_execution_or_io(self):
        program = '''
import sys
forbidden = {"groq", "httpx", "controlled_agent.controller", "controlled_agent.provider_host",
             "controlled_agent.executor", "controlled_agent.audit", "controlled_agent.demo_tools"}
def block(event, args):
    if event == "import" and args[0] in forbidden:
        raise AssertionError("Forbidden import")
    if event.startswith("socket.") or event == "builtins.input":
        raise AssertionError("Forbidden I/O")
    if event == "open" and (args[2] & 3):
        raise AssertionError("Forbidden write")
sys.addaudithook(block)
from controlled_agent.proposal_evaluation import assess, ResponseObservation
result = assess([("N1", ResponseObservation(response=None))])
assert result.intent_matches == 1
assert not forbidden.intersection(sys.modules)
'''
        result = subprocess.run([sys.executable, "-B", "-S", "-c", program],
                                cwd=Path(__file__).resolve().parents[1], env={},
                                capture_output=True, timeout=20)
        self.assertEqual(result.returncode, 0, result.stderr.decode())


